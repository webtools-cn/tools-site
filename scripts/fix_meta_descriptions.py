count = 0
for tool, new_desc in targets.items():
    path = os.path.join(ROOT, tool, 'index.html')
    if not os.path.exists(path):
        print(f'NOT FOUND: {tool}')
        continue
    with open(path, 'r') as fh:
        content = fh.read()
    
    m = re.search(r'<meta name="description" content="([^"]*)"', content)
    if not m:
        print(f'NO DESC: {tool}')
        continue
    
    old_desc = m.group(1)
    old_full = m.group(0)
    new_full = '<meta name="description" content="' + new_desc + '"'
    
    content = content.replace(old_full, new_full, 1)
    
    with open(path, 'w') as fh:
        fh.write(content)
    count += 1
    print(f'OK: {tool} [{len(old_desc)}c -> {len(new_desc)}c]')

print(f'\nTotal fixed: {count}')