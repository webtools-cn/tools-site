def fix_page(tool_dir, old_desc, new_desc):
    path = f"{tool_dir}/index.html"
    if not os.path.exists(path):
        print(f"  SKIP {tool_dir}: file not found")
        return False
    
    with open(path) as fh:
        content = fh.read()
    
    if old_desc not in content:
        print(f"  SKIP {tool_dir}: old desc not found")
        return False
    
    # Replace in meta description
    new_content = content.replace(
        f'<meta name="description" content="{old_desc}"',
        f'<meta name="description" content="{new_desc}"'
    )
    
    # Replace in og:description
    new_content = new_content.replace(
        f'<meta property="og:description" content="{old_desc}"',
        f'<meta property="og:description" content="{new_desc}"'
    )
    
    # Replace in Schema.org description (may vary slightly)
    if f'"description": "{old_desc}"' in new_content:
        new_content = new_content.replace(
            f'"description": "{old_desc}"',
            f'"description": "{new_desc}"'
        )
    
    # Also fix H1 titles for pages with broken titles
    with open(path, 'w') as fh:
        fh.write(new_content)
    
    print(f"  OK {tool_dir}: {len(old_desc)}→{len(new_desc)} chars")
    return True

fixed = 0
skipped = 0
for tool_dir, old_desc, new_desc in FIXES:
    print(f"Processing {tool_dir}...")
    if fix_page(tool_dir, old_desc, new_desc):
        fixed += 1
    else:
        skipped += 1

print(f"\nDone: {fixed} fixed, {skipped} skipped")
