def update_page(dirname, old_meta, new_meta, old_og, new_og):
    path = os.path.join(dirname, 'index.html')
    with open(path, 'r') as f:
        content = f.read()

    content = content.replace(old_meta, new_meta)
    content = content.replace(old_og, new_og)

    with open(path, 'w') as f:
        f.write(content)

    m = re.search(r'<meta name="description" content="([^"]+)"', content)
    new_len = len(m.group(1)) if m else 0
    status = '✅' if 140 <= new_len <= 160 else f'❌({new_len})'
    print(f'  {status} {dirname}: {new_len} chars')

def main():
    # Read current descriptions from files
    for dirname in PAGES:
        path = os.path.join(dirname, 'index.html')
        with open(path, 'r') as f:
            content = f.read()
        meta_m = re.search(r'<meta name="description" content="([^"]+)"', content)
        og_m = re.search(r'<meta property="og:description" content="([^"]+)"', content)
        if meta_m:
            old_meta = meta_m.group(0)
            old_og = og_m.group(0) if og_m else ''
            new_meta = f'<meta name="description" content="{PAGES[dirname]["meta"]}">'
            new_og = f'<meta property="og:description" content="{PAGES[dirname]["og"]}">'
            print(f'Updating {dirname}...')
            update_page(dirname, old_meta, new_meta, old_og, new_og)

if __name__ == '__main__':
    main()