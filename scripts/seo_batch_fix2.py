count = 0
for tool, data in tools_desc.items():
    fpath = f"{tool}/index.html"
    try:
        content = open(fpath).read()
        
        # 替换 meta description
        old = f'<meta name="description" content="{data["old_desc"]}">'
        if old in content:
            content = content.replace(old, f'<meta name="description" content="{data["new_desc"]}">')
        else:
            m = re.search(r'<meta name="description" content="([^"]+)">', content)
            if m:
                content = content.replace(m.group(0), f'<meta name="description" content="{data["new_desc"]}">')
        
        # 替换 og:description
        old_og = f'<meta property="og:description" content="{data["old_desc"]}">'
        if old_og in content:
            content = content.replace(old_og, f'<meta property="og:description" content="{data["new_og_desc"]}">')
        else:
            m2 = re.search(r'<meta property="og:description" content="([^"]+)">', content)
            if m2:
                content = content.replace(m2.group(0), f'<meta property="og:description" content="{data["new_og_desc"]}">')
        
        # 替换 ld+json SoftwareApplication description  
        ld_pattern = '"description":"' + re.escape(data["old_desc"]) + '"'
        content = re.sub(ld_pattern, f'"description":"{data["new_og_desc"]}"', content)
        
        # 也替换其他ld+json中的旧描述
        content = re.sub(
            '"description":"' + re.escape(data["old_desc"]) + '"',
            f'"description":"{data["new_og_desc"]}"',
            content
        )
        
        open(fpath, 'w').write(content)
        new_len = len(data["new_desc"])
        print(f"✅ {tool}: {len(data['old_desc'])} -> {new_len} chars")
        count += 1
    except Exception as e:
        print(f"❌ {tool}: {e}")

print(f"\n第2批完成: {count}/20 个页面已优化")