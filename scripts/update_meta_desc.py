success = 0
failed = []

for path, old_desc, new_desc in updates:
    with open(path, 'r', encoding='utf-8', errors='ignore') as fh:
        content = fh.read()
    
    if old_desc not in content:
        failed.append((path, 'old_desc not found in file'))
        continue
    
    new_len = len(new_desc)
    if new_len < 140 or new_len > 165:
        failed.append((path, f'new desc length {new_len} (target 140-160)'))
        continue
    
    new_content = content.replace(old_desc, new_desc)
    if new_content == content:
        failed.append((path, 'replace produced no change'))
        continue
    
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(new_content)
    
    success += 1
    print(f'OK: {path} (was {len(old_desc)} -> now {new_len} chars)')

if failed:
    print(f'\nFAILED ({len(failed)}):')
    for p, reason in failed:
        print(f'  {p}: {reason}')

print(f'\nTotal: {success} updated, {len(failed)} failed')