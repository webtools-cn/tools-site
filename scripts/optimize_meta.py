import os, re

skip = {'en','css','js','scripts','quality','chrome-extension','docs','cron-reports','.gsc-data','.git'}

for d, new_desc in NEW_DESCRIPTIONS.items():
    f = os.path.join(d, 'index.html')
    if not os.path.exists(f):
        print(f"SKIP {d}: no file")
        continue
    
    with open(f) as fh:
        content = fh.read()
    
    old_m = re.search(r'<meta name="description" content="[^"]*"', content)
    if not old_m:
        print(f"SKIP {d}: no meta description")
        continue
    
    old_str = old_m.group(0)
    new_str = f'<meta name="description" content="{new_desc}"'
    
    content = content.replace(old_str, new_str, 1)
    
    with open(f, 'w') as fh:
        fh.write(content)
    
    new_len = len(new_desc)
    print(f"OK {d}: {len(old_str)} -> {new_len} chars")

print("\n=== Done! ===")
print(f"Updated {len(NEW_DESCRIPTIONS)} pages")