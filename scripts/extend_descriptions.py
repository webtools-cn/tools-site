import os, sys

fixed = 0
for tool_dir, old_desc, new_desc in FIXES:
    path = f"{tool_dir}/index.html"
    if not os.path.exists(path):
        print(f"  SKIP {tool_dir}: file not found")
        continue
    
    with open(path) as fh:
        content = fh.read()
    
    if old_desc not in content:
        print(f"  SKIP {tool_dir}: old desc not found (length={len(old_desc)})")
        continue
    
    # Replace in all three locations
    new_content = content.replace(old_desc, new_desc)
    
    with open(path, 'w') as fh:
        fh.write(new_content)
    
    print(f"  OK {tool_dir}: {len(old_desc)}→{len(new_desc)} chars")
    fixed += 1

print(f"\nDone: {fixed} fixed")
